#!/usr/bin/env python3
"""P1-07: build docs/component-colours.md — inventory of the 171 component colours (D-05: preserve, document only).

Usage: python3 -I scripts/build-component-colours.py registry/raw/figma-variables-<date>.json \
           registry/raw/figma-colour-usage-<date>.json docs/component-colours.md
Local files only. Never talks to Figma; never writes outside this workspace.
"""
import json, sys
from collections import Counter, defaultdict

PRESERVE = 'preserve; not migrated (D-05)'


def main(var_path, usage_path, out_path):
    V = json.load(open(var_path)); U = json.load(open(usage_path))
    prim = {r[0]: r[2] for r in V['_Primitives']['rows']}
    cm = {r[0]: r[1:] for r in V['1. Color modes']['rows']}

    def resolve(val, i, depth=0):
        if depth > 6: return '?'
        if val.startswith('P:'): return prim[val[2:]]
        if val.startswith('C:'): return resolve(cm[val[2:]][i], i, depth + 1)
        return val

    def show(val, i):
        hx = resolve(val, i)
        if val.startswith('P:'): return f"{val[2:].replace('Colors/', '')} `{hx}`"
        if val.startswith('C:'): return f"→ {val[2:].split('/')[-1]} `{hx}`"
        return f"raw `{hx}`"

    comp = [(n, v) for n, v in cm.items() if n.startswith('Component colors/')]
    core = [(n, v) for n, v in cm.items() if n.startswith('Colors/')]

    # Usage: variable name -> {component: count}
    usage = defaultdict(Counter)
    for it in U['items']:
        for var, (direct, via) in it['colours'].items():
            usage[var.replace(' (remote)', '')][it['name']] += direct + via

    # PROPOSED equivalents: exact alias match first, then same resolved values in both modes.
    by_alias = defaultdict(list); by_hex = defaultdict(list)
    for n, v in core:
        by_alias[tuple(v)].append(n)
        by_hex[(resolve(v[0], 0).lower(), resolve(v[1], 1).lower())].append(n)

    def suggest(n, v):
        a = by_alias.get(tuple(v))
        if a: return 'same aliases as ' + ', '.join(f"`{x.split('/')[-1]}`" for x in a), 'exact'
        h = by_hex.get((resolve(v[0], 0).lower(), resolve(v[1], 1).lower()))
        if h: return 'same values as ' + ', '.join(f"`{x.split('/')[-1]}`" for x in h), 'value'
        if '/Utility/' in n: return 'none — utility palette scale; keep as component-level scale', 'none'
        if '/Alpha/' in n: return 'none — alpha scale (inverts in dark mode); candidate for an opacity utility', 'none'
        return 'none found', 'none'

    rows = []
    for n, v in comp:
        group = n.split('/')[1] if n.split('/')[1] != 'Components' else 'Components/' + n.split('/')[2]
        if n.split('/')[1] == 'Utility': group = 'Utility/' + n.split('/')[2]
        s, kind = suggest(n, v)
        used = usage.get(n, {})
        rows.append({'name': n, 'group': group, 'light': show(v[0], 0), 'dark': show(v[1], 1),
                     'used': ', '.join(f"{c} ({k})" for c, k in sorted(used.items())) or '—',
                     'usedCount': len(used), 'suggest': s, 'kind': kind,
                     'rawLight': not v[0][:2] in ('P:', 'C:'), 'rawDark': not v[1][:2] in ('P:', 'C:')})

    grp = Counter(r['group'].split('/')[0] for r in rows)
    used_n = sum(1 for r in rows if r['usedCount'])
    kinds = Counter(r['kind'] for r in rows)
    raw_any = [r for r in rows if r['rawLight'] or r['rawDark']]
    direct_prims = defaultdict(Counter); remote = defaultdict(Counter)
    for it in U['items']:
        for var, (d, s) in it['colours'].items():
            if var.endswith(' (remote)'): remote[it['name']][var] += d + s
            elif not var.startswith(('Colors/Text', 'Colors/Border', 'Colors/Foreground', 'Colors/Background', 'Colors/Effects', 'Component colors/')):
                direct_prims[it['name']][var] += d + s

    L = []; w = L.append
    w('# Component colours — inventory (D-05)\n')
    w('> **Status:** documentation only (task P1-07, 2026-11-09). Decision **D-05: preserve current appearance; do not migrate, rename, remap or delete.** Every row below is `' + PRESERVE + '`. "Suggested future equivalent" is **PROPOSED** for later evaluation, not approved.\n')
    w('Source: live read of MAKER-DS-v2 `xJoAz66aekAToyhBmfGNt0` (`registry/raw/figma-variables-2026-11-09.json`), usage from a read-only scan of every component\'s own layers (`registry/raw/figma-colour-usage-2026-11-09.json`, `scripts/figma-colour-usage-scan.js`). Generated by `scripts/build-component-colours.py`.\n')
    w('## Summary (VERIFIED)\n')
    w(f"- **{len(rows)} component colours** in `1. Color modes` (Light / Dark). Groups: " + ', '.join(f"{k} {v}" for k, v in grp.most_common()) + '.')
    w(f"- **{used_n} of {len(rows)} are used** by a component in this library (own layers, any variant). The other {len(rows) - used_n} are not referenced by any MAKER DS v2 component; they may still be used in consumer files (UNVERIFIED).")
    w(f"- **Alias structure:** {len(rows) - len(raw_any)} alias primitives (or other colour-mode variables) in both modes; {len(raw_any)} hold a raw value in at least one mode (Alpha scale, app-store badge border, avatar neutral bg).")
    w(f"- **Suggested equivalents (PROPOSED):** {kinds['exact']} have a core semantic variable with the same aliases in both modes; {kinds['value']} match a core variable by value only; {kinds['none']} have no core equivalent (mostly Utility palette scales and the Alpha scale).\n")
    w('## Related findings (VERIFIED, outside D-05 scope)\n')
    w('- **Components bound directly to primitives** (bypassing the semantic layer): ' + '; '.join(f"{c}: " + ', '.join(f"`{v}` ×{k}" for v, k in cnt.items()) for c, cnt in direct_prims.items()) + '.')
    w('- **Components bound to remote colour variables** (another library\'s variables, not this file\'s): ' + '; '.join(f"{c}: " + ', '.join(f"`{v}` ×{k}" for v, k in cnt.items()) for c, cnt in remote.items()) + '. Which library is UNVERIFIED.\n')
    w('## Inventory\n')
    w('Light / Dark: alias target (primitive or `→` another colour-mode variable) and resolved hex. "Used by": component (number of colour bindings across all variants: solid fills, solid strokes and effect colours on the component’s own layers).\n')
    cur = None
    n = 0
    for r in sorted(rows, key=lambda r: (r['group'], r['name'])):
        if r['group'] != cur:
            cur = r['group']
            w(f"\n### {cur}\n")
            w('| # | Variable | Light | Dark | Used by | Suggested future equivalent (PROPOSED) | Status |')
            w('|---|---|---|---|---|---|---|')
        n += 1
        w(f"| {n} | `{r['name'].split('/')[-1]}` | {r['light']} | {r['dark']} | {r['used']} | {r['suggest']} | {PRESERVE} |")
    w('\n## Validation\n')
    w(f"- Row count: **{n}** (expected 171 from the `1. Color modes` collection: 292 − 121 core). {'✓' if n == 171 else '✗ MISMATCH'}")
    w(f"- Every row carries the status `{PRESERVE}`.")
    w('- No Figma variable, token or binding was changed. Usage scan and variable read were read-only `use_figma` calls.')
    open(out_path, 'w').write('\n'.join(L) + '\n')
    return n, used_n, kinds, len(raw_any), direct_prims, remote


if __name__ == '__main__':
    n, used_n, kinds, raw_n, dp, rm = main(*sys.argv[1:4])
    print('rows', n, 'used', used_n, dict(kinds), 'raw-valued', raw_n)
    print('direct primitives:', {k: dict(v) for k, v in dp.items()})
    print('remote:', {k: dict(v) for k, v in rm.items()})
    if n != 171: sys.exit(1)
